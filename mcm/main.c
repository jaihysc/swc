// Periodic update

static void update(struct btstack_timer_source* ts) {
    // Count sense oscillator edge transitions
    int16_t counts = 0;
    bool valPrev = gpio_get(15);
    for (int i = 0; i < SOSC_COUNTS; ++i) {
        bool val = gpio_get(15);
        if (val != valPrev) {
            ++counts;
        }
        valPrev = val;
    }

    // Edge transition within threshold = 1 vote
    // Detect if enough consecutive votes
    int16_t countDelta = abs(uData.soscCountsPrev - counts);
    if (countDelta > SOSC_VOTE_MIN_TH && countDelta < SOSC_VOTE_MAX_TH) {
        ++uData.soscDetectVote;
    }

    // Make decision after measurements
    bool detected = false;
    ++uData.soscDetectIter;
    if (uData.soscDetectIter >= SOSC_DET_ITER) {
        if (uData.soscDetectVote >= SOSC_DET_TH) {
            detected = true;
            // Update counts to avoid re-detection
            uData.soscCountsPrev = counts;
        }
        else if (uData.soscDetectVote == 0) {
            // Update counts when certain is idle
            uData.soscCountsPrev = counts;
        }
        // Update for next measurement
        uData.soscDetectVote = 0;
        uData.soscDetectIter = 0;
    }



    // Pulse LED if detected
    if (detected) {
        gpio_set_mask(1);
    }
    else {
        gpio_clr_mask(1);
    }


    // Charger test
    if (gpio_get(12)) {
        statusSet(STATUS_TRANSIT);
    }
    else {
        statusSet(STATUS_IDLE);
    }

    statusUpdate();

    // Restart timer
    btstack_run_loop_set_timer(ts, HEARTBEAT_PERIOD_MS);
    btstack_run_loop_add_timer(ts);
}

// Init

int main() {
    // Initialize CYW43 driver architecture (will enable BT if/because CYW43_ENABLE_BLUETOOTH == 1)
    if (cyw43_arch_init()) {
        return 1; // Can't use LED if this fails
    }

    gpio_init(0);
    gpio_set_dir(0, GPIO_OUT);
    gpio_init(15);
    gpio_set_dir(15, GPIO_IN);
    gpio_init(12);
    gpio_set_dir(12, GPIO_IN);

    // Initialize bluetooth
    l2cap_init();
    sm_init();

    btPacketRegistration.callback = &packetHandler;
    hci_add_event_handler(&btPacketRegistration);

    btTimer.process = &update;
    btstack_run_loop_set_timer(&btTimer, HEARTBEAT_PERIOD_MS);
    btstack_run_loop_add_timer(&btTimer);

    att_server_init(profile_data, attRead, attWrite);
    att_server_register_packet_handler(packetHandler);

    // Turn on bluetooth
    if (hci_power_control(HCI_POWER_ON)) {
        statusSet(STATUS_BT_ERR);
    }

    // In this loop the Bluetooth events will run
    while (1) {
    }
    return 0;
}