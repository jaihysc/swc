#define HEARTBEAT_PERIOD_MS 100
#define APP_AD_FLAGS 0x06

enum
{
    SOSC_COUNTS       = (1 << 20),
    SOSC_DET_ITER     = 16,  // Number of measurements before making decision
    SOSC_DET_TH       = 10,  // Number of times in threshold (votes) to declare detected
    SOSC_VOTE_MIN_TH  = 5,   // Threshold: 2^20 / Fclk * dF
                             // Fclk = 120 MHz
                             // dF = 1 kHz (change in frequency with phone)
    SOSC_VOTE_MAX_TH  = 500, // Significant frequency changes from charger ping ignored
                             // dF = 100 kHz
};

extern const uint8_t profile_data[]; // Autogenerated for GATT profile

// Data

static uint8_t btAdvertisement[] = {
    // Flags general discoverable
    2, BLUETOOTH_DATA_TYPE_FLAGS, APP_AD_FLAGS,
    // Name
    1+7, BLUETOOTH_DATA_TYPE_COMPLETE_LOCAL_NAME, 'S', 'C', 'W', ' ', 'M', 'C', 'M',
    3, BLUETOOTH_DATA_TYPE_COMPLETE_LIST_OF_16_BIT_SERVICE_CLASS_UUIDS, 0x1a, 0x18,
};

static btstack_timer_source_t btTimer;
static btstack_packet_callback_registration_t btPacketRegistration;

static struct
{
    // Phone detection
    int16_t soscCountsPrev;
    uint8_t soscDetectVote;
    uint8_t soscDetectIter;
} uData;

// Bluetooth events

static void packetHandler(uint8_t packet_type, uint16_t channel, uint8_t *packet, uint16_t size) {
    UNUSED(size);
    UNUSED(channel);

    if (packet_type != HCI_EVENT_PACKET) return;

    uint8_t event_type = hci_event_packet_get_type(packet);
    switch (event_type) {
        case BTSTACK_EVENT_STATE:
            if (btstack_event_state_get_state(packet) == HCI_STATE_WORKING) {
                // Bluetooth running

                // Setup advertisements
                uint16_t adv_int_min = 800;
                uint16_t adv_int_max = 800;
                uint8_t adv_type = 0;
                bd_addr_t null_addr;
                memset(null_addr, 0, 6);
                gap_advertisements_set_params(adv_int_min, adv_int_max, adv_type, 0, null_addr, 0x07, 0x00);

                gap_advertisements_set_data(sizeof(btAdvertisement), btAdvertisement);
                gap_advertisements_enable(1);

                statusSet(STATUS_IDLE);
            }
            break;

        default:
            break;
    }
}

